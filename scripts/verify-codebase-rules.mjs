import fs from "node:fs";
import path from "node:path";

const projectRoot = path.resolve(".");
const dirsToScan = ["src", "public", "scripts"];
const filesToScan = ["package.json", "next.config.ts", "tailwind.config.ts", "README.md", "DEPLOY.md"];

const forbiddenChecks = [
  {
    name: "Em dashes or en dashes",
    regex: /[\u2013\u2014]|&mdash;|&ndash;/g,
  },
  {
    name: "Gradients",
    regex: /bg-gradient|linear-gradient|radial-gradient/gi,
  },
  {
    name: "Rounded full class",
    regex: /\brounded-full\b/g,
  },
  {
    name: "Generator badges or AI mentions",
    regex: /\b(Made with|Built with|Generated by|v0\.dev|lovable\.dev|bolt\.new|chatgpt|openai)\b/gi,
  },
  {
    name: "Fake popularity or review markers",
    regex: /\b(bestseller|most loved|trending|5-star|4\.9\/5|fake review)\b/gi,
  },
  {
    name: "Emojis",
    regex: /[\u{1F300}-\u{1F9FF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}]/u,
  },
];

function getAllFiles(dirPath, arrayOfFiles = []) {
  if (!fs.existsSync(dirPath)) return arrayOfFiles;
  const entries = fs.readdirSync(dirPath, { withFileTypes: true });

  for (const entry of entries) {
    const fullPath = path.join(dirPath, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== "node_modules" && entry.name !== ".next") {
        getAllFiles(fullPath, arrayOfFiles);
      }
    } else {
      arrayOfFiles.push(fullPath);
    }
  }
  return arrayOfFiles;
}

let allFiles = [];
for (const dir of dirsToScan) {
  allFiles = getAllFiles(path.join(projectRoot, dir), allFiles);
}
for (const file of filesToScan) {
  const fullPath = path.join(projectRoot, file);
  if (fs.existsSync(fullPath)) {
    allFiles.push(fullPath);
  }
}

// Filter to code and text files
allFiles = allFiles.filter((f) => {
  const ext = path.extname(f).toLowerCase();
  return [".ts", ".tsx", ".js", ".mjs", ".json", ".css", ".md", ".svg"].includes(ext);
});

console.log(`\nScanning ${allFiles.length} files against strict rules...\n`);

let violationsCount = 0;

for (const filePath of allFiles) {
  const relPath = path.relative(projectRoot, filePath);
  // Skip this verification script itself
  if (relPath.includes("verify-codebase-rules.mjs")) continue;

  const content = fs.readFileSync(filePath, "utf-8");
  const lines = content.split(/\r?\n/);

  lines.forEach((line, index) => {
    // Skip code comments in script or config if explaining rules
    const trimmed = line.trim();

    for (const check of forbiddenChecks) {
      check.regex.lastIndex = 0;
      if (check.regex.test(line)) {
        // Exception for intentional "Website by" check in check-placeholders or README
        if (check.name === "Generator badges or AI mentions" && (relPath.includes("check-placeholders.mjs") || relPath.includes("README.md"))) {
          continue;
        }

        console.error(`[VIOLATION] ${check.name} in ${relPath}:${index + 1}`);
        console.error(`   Line: ${trimmed.slice(0, 100)}`);
        violationsCount++;
      }
    }
  });
}

console.log("\n--------------------------------------------------------");
if (violationsCount === 0) {
  console.log("PASS: 0 violations found. The codebase strictly complies with all rules.");
  process.exit(0);
} else {
  console.error(`FAIL: Found ${violationsCount} violation(s). Please fix before proceeding.`);
  process.exit(1);
}
